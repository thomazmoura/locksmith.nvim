local store = require("locksmith.store")

--- A store created with `password`, holding secrets, config and a cache: returns the module,
--- locked
local function with_store(password)
  local ls = T.fresh()
  ls.set_prompt(T.script({ password, password }).fn)
  T.await(function(done)
    ls.set("ns", "pat", "s3cret", done)
  end)
  T.await(function(done)
    ls.set("ns", "settings", { a = 1 }, done)
  end)
  T.await(function(done)
    ls.set("other", "token", "t0ken", done)
  end)
  T.await(function(done)
    ls.cache("ns").save("contacts", { "Ana" }, done)
  end)
  ls.lock()
  return ls
end

--- Every file of the store (data and cache): { path = content }
local function snapshot()
  local files = {}
  for _, root in ipairs({ store.data_dir(), store.cache_dir() }) do
    for _, path in ipairs(vim.fn.globpath(root, "**/*.json", true, true)) do
      files[path] = T.read(path)
    end
    files[root .. "/store.json"] = T.read(root .. "/store.json")
  end
  return files
end

local function get(ls, namespace, name)
  return T.await(function(done)
    ls.get(namespace, name, done)
  end)
end

T.test("after a password change every item is readable and only store.json changed", function()
  local ls = with_store("old")
  local before = snapshot()
  ls.set_prompt(T.script({ "old", "new", "new" }).fn)
  T.eq({ T.await(ls.change_password) }, { true })
  local after = snapshot()
  for path, content in pairs(before) do
    if vim.fs.basename(path) == "store.json" and path:find(store.data_dir(), 1, true) then
      T.ok(after[path] ~= content, "store.json unchanged")
    else
      T.eq(after[path], content, path)
    end
  end
  T.eq(vim.tbl_count(after), vim.tbl_count(before))
  ls.lock()
  ls.set_prompt(T.script({ "new" }).fn)
  T.eq(get(ls, "ns", "pat"), "s3cret")
  T.eq(get(ls, "ns", "settings"), { a = 1 })
  T.eq(get(ls, "other", "token"), "t0ken")
  T.eq(T.await(function(done)
    ls.cache("ns").load("contacts", done)
  end), { "Ana" })
  ls.lock()
  ls.set_prompt(T.script({ "old", nil }).fn)
  T.eq(T.await(ls.unlock), nil)
end)

T.test("the password change uses the configured KDF parameters", function()
  local ls = with_store("old")
  ls.setup({ kdf = { t = 2 } })
  ls.set_prompt(T.script({ "old", "new", "new" }).fn)
  T.await(ls.change_password)
  T.eq(ls.status().kdf.t, 2)
end)

T.test("a second session holding the old data key keeps working", function()
  local ls = with_store("old")
  ls.set_prompt(T.script({ "old" }).fn)
  T.eq(get(ls, "ns", "pat"), "s3cret")
  local second = ls
  local first = T.instance()
  first.set_prompt(T.script({ "old", "new", "new" }).fn)
  T.eq(T.await(first.change_password), true)
  -- No prompt: the data key did not change
  second.set_prompt(T.script({}).fn)
  T.eq(get(second, "ns", "pat"), "s3cret")
  T.eq(T.await(function(done)
    second.set("ns", "pat", "updated", done)
  end), true)
  first.set_prompt(T.script({}).fn)
  T.eq(get(first, "ns", "pat"), "updated")
end)

T.test("a wrong current password changes nothing", function()
  local ls = with_store("old")
  local before = snapshot()
  ls.set_prompt(T.script({ "nope" }).fn)
  local ok, err = T.await(ls.change_password)
  T.eq(ok, nil)
  T.ok(err:find("wrong password"))
  T.eq(snapshot(), before)
end)

T.test("a failing set_password_check leaves the store untouched", function()
  local ls = with_store("old")
  local before = snapshot()
  local checked = {}
  ls.set_password_check(function(password, callback)
    table.insert(checked, password)
    vim.defer_fn(function()
      callback(false, "Exchange said no")
    end, 10)
  end)
  ls.set_prompt(T.script({ "old", "new", "new" }).fn)
  local ok, err = T.await(ls.change_password)
  T.eq(ok, nil)
  T.ok(err:find("Exchange said no"))
  T.eq(checked, { "new" })
  T.eq(snapshot(), before)
end)

T.test("my password changed: the previous one opens the store, re-wrapped with the new one", function()
  local ls = with_store("old")
  local seen = {}
  ls.on_unlock(function(password)
    table.insert(seen, password)
  end)
  local prompt = T.script({ "new", 2, "old", "new" })
  ls.set_prompt(prompt.fn)
  T.eq(get(ls, "ns", "pat"), "s3cret")
  T.eq(seen, { "new" })
  T.eq(#prompt.calls, 4)
  ls.lock()
  ls.set_prompt(T.script({ "new" }).fn)
  T.eq(get(ls, "other", "token"), "t0ken")
end)

T.test("my password changed: confirmed by set_password_check instead of typed again", function()
  local ls = with_store("old")
  ls.set_password_check(function(password, callback)
    callback(password == "new")
  end)
  local prompt = T.script({ "new", 2, "old" })
  ls.set_prompt(prompt.fn)
  T.eq(get(ls, "ns", "pat"), "s3cret")
  T.eq(#prompt.calls, 3)
end)

T.test("my password changed: a failing check leaves the store untouched", function()
  local ls = with_store("old")
  local before = snapshot()
  ls.set_password_check(function(_, callback)
    callback(false, "bad")
  end)
  ls.set_prompt(T.script({ "typo", 2, "old" }).fn)
  local value, err = get(ls, "ns", "pat")
  T.eq(value, nil)
  T.ok(err:find("not changed"))
  T.eq(snapshot(), before)
end)

T.test("my password changed: a wrong previous password goes back to the menu", function()
  local ls = with_store("old")
  local prompt = T.script({ "new", 2, "older", 1, "old" })
  ls.set_prompt(prompt.fn)
  T.eq(get(ls, "ns", "pat"), "s3cret")
  T.eq(prompt.calls[4].kind, "choice")
end)

T.test("reset deletes everything only after confirmation, then a new store is created", function()
  local ls = with_store("old")
  local before = snapshot()
  local prompt = T.script({ "forgot", 3, "no" })
  ls.set_prompt(prompt.fn)
  T.eq(get(ls, "ns", "pat"), nil)
  T.eq(snapshot(), before)
  -- The confirmation lists what is lost
  T.ok(prompt.calls[3].message:find("ns: pat, settings", 1, true))
  T.ok(prompt.calls[3].message:find("other: token", 1, true))
  T.ok(prompt.calls[3].message:find("caches of ns", 1, true))

  ls.set_prompt(T.script({ "forgot", 3, "yes", "fresh", "fresh" }).fn)
  T.eq(T.await(ls.unlock), true)
  T.eq(ls.namespaces(), {})
  T.eq(vim.uv.fs_stat(store.cache_dir()), nil)
  T.eq(ls.status().exists, true)
  ls.lock()
  ls.set_prompt(T.script({ "fresh" }).fn)
  T.eq(T.await(ls.unlock), true)
end)

T.test("reset() asks for confirmation too", function()
  local ls = with_store("old")
  ls.set_prompt(T.script({ "nah" }).fn)
  T.eq(T.await(ls.reset), nil)
  T.eq(ls.status().exists, true)
  ls.set_prompt(T.script({ "yes" }).fn)
  T.eq(T.await(ls.reset), true)
  T.eq(ls.status().exists, false)
  T.eq(ls.namespaces(), {})
end)
