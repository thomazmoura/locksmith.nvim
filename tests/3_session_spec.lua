local crypto = require("locksmith.crypto")

--- A store created with `password`, holding ns/pat = "s3cret": returns the module, locked
local function with_store(password, opts)
  local ls = T.fresh(opts)
  local prompt = T.script({ password, password })
  ls.set_prompt(prompt.fn)
  T.eq({ T.await(function(done)
    ls.set("ns", "pat", "s3cret", done)
  end) }, { true })
  ls.lock()
  return ls
end

T.test("the first unlock creates the store, the password typed twice", function()
  local ls = T.fresh()
  local prompt = T.script({ "pw", "pw" })
  ls.set_prompt(prompt.fn)
  T.eq(ls.status().exists, false)
  T.eq({ T.await(ls.unlock) }, { true })
  T.eq(#prompt.calls, 2)
  T.eq(prompt.calls[1].kind, "password")
  local status = ls.status()
  T.eq(status.exists, true)
  T.eq(status.unlocked, true)
  T.eq(status.dek_generation, 1)
  T.eq(status.kdf, T.KDF)
end)

T.test("a mismatched new password is asked again, then given up", function()
  local ls = T.fresh()
  ls.set_prompt(T.script({ "a", "b", "c", "d" }).fn)
  local ok, err = T.await(ls.unlock)
  T.eq(ok, nil)
  T.ok(err:find("do not match"))
  T.eq(ls.status().exists, false)
end)

T.test("get, set, delete and list secrets and config", function()
  local ls = with_store("pw")
  ls.set_prompt(T.script({ "pw" }).fn)
  T.eq(T.await(function(done)
    ls.get("ns", "pat", done)
  end), "s3cret")
  local config = { url = "https://dev.azure.com/org", projects = { "a", "b" }, nested = { n = 1 } }
  T.eq(T.await(function(done)
    ls.set("ns", "settings", config, done)
  end), true)
  T.eq(T.await(function(done)
    ls.get("ns", "settings", done)
  end), config)
  T.eq(ls.list("ns"), { "pat", "settings" })
  T.eq(ls.namespaces(), { "ns" })
  T.eq({ T.await(function(done)
    ls.get("ns", "missing", done)
  end) }, { nil, nil })
  T.await(function(done)
    ls.delete("ns", "pat", done)
  end)
  T.eq(ls.list("ns"), { "settings" })
  T.eq(ls.list("empty"), {})
end)

T.test("reading a missing item does not prompt", function()
  local ls = with_store("pw")
  local prompt = T.script({})
  ls.set_prompt(prompt.fn)
  T.eq({ T.await(function(done)
    ls.get("ns", "nothing", done)
  end) }, { nil, nil })
  T.eq(#prompt.calls, 0)
end)

T.test("concurrent gets cause one prompt", function()
  local ls = with_store("pw")
  local prompt = T.script({ "pw" }, 30)
  ls.set_prompt(prompt.fn)
  local results = {}
  for i = 1, 3 do
    ls.get("ns", "pat", function(value, err)
      results[i] = { value, err }
    end)
  end
  ls.cache("other").save("x", { 1 }, function(ok)
    results[4] = { ok }
  end)
  T.ok(vim.wait(5000, function()
    return #vim.tbl_keys(results) == 4
  end))
  T.eq(results, { { "s3cret" }, { "s3cret" }, { "s3cret" }, { true } })
  T.eq(#prompt.calls, 1)
end)

T.test("a wrong password, then retry", function()
  local ls = with_store("pw")
  local prompt = T.script({ "typo", 1, "pw" })
  ls.set_prompt(prompt.fn)
  T.eq(T.await(function(done)
    ls.get("ns", "pat", done)
  end), "s3cret")
  T.eq(#prompt.calls, 3)
  T.eq(prompt.calls[2].kind, "choice")
  T.ok(prompt.calls[2].message:find("1. Retry"))
end)

T.test("declining the password fails without asking again, until unlock()", function()
  local ls = with_store("pw")
  local prompt = T.script({ nil, "pw" })
  ls.set_prompt(prompt.fn)
  local value, err = T.await(function(done)
    ls.get("ns", "pat", done)
  end)
  T.eq(value, nil)
  T.ok(err:find("not entered"))
  T.await(function(done)
    ls.get("ns", "pat", done)
  end)
  T.eq(#prompt.calls, 1)
  T.eq(T.await(ls.unlock), true)
  T.eq(#prompt.calls, 2)
end)

T.test("on_unlock gets the password once, and only after a successful unlock", function()
  local ls = with_store("pw")
  local seen = {}
  T.eq(ls.on_unlock(function(password)
    table.insert(seen, password)
  end), true)
  ls.set_prompt(T.script({ "wrong", 1, "pw" }).fn)
  T.await(ls.unlock)
  T.eq(seen, { "pw" })
  ls.lock()
  ls.set_prompt(T.script({ "pw" }).fn)
  T.await(ls.unlock)
  T.eq(seen, { "pw" })
  -- Registered while unlocked: not called, the consumer asks itself
  T.eq(ls.on_unlock(function(password)
    table.insert(seen, password)
  end), false)
  T.settle()
  T.eq(seen, { "pw" })
end)

T.test("on_unlock is not called when the unlock fails", function()
  local ls = with_store("pw")
  local seen = {}
  ls.on_unlock(function(password)
    table.insert(seen, password)
  end)
  ls.set_prompt(T.script({ "wrong", nil }).fn)
  T.eq(T.await(ls.unlock), nil)
  T.eq(seen, {})
end)

T.test("lock() zeroes the data key", function()
  local ls = with_store("pw")
  ls.set_prompt(T.script({ "pw" }).fn)
  T.await(ls.unlock)
  local dek = ls._state.dek
  T.ok(dek and not crypto.is_zero(dek))
  ls.lock()
  T.ok(crypto.is_zero(dek))
  T.eq(ls._state.dek, nil)
  T.eq(ls.status().unlocked, false)
end)

T.test("caches round trip, and are not readable under another namespace", function()
  local ls = with_store("pw")
  ls.set_prompt(T.script({ "pw" }).fn)
  local a, b = ls.cache("a"), ls.cache("b")
  T.eq(T.await(function(done)
    a.save("contacts", { { name = "Ana" } }, done)
  end), true)
  T.eq(T.await(function(done)
    a.load("contacts", done)
  end), { { name = "Ana" } })
  local store = require("locksmith.store")
  vim.fn.mkdir(store.cache_dir() .. "/b", "p")
  vim.uv.fs_copyfile(store.item_path("cache", "a", "contacts"), store.item_path("cache", "b", "contacts"))
  T.eq(T.await(function(done)
    b.load("contacts", done)
  end), nil)
  -- Undecryptable: dropped
  T.eq(vim.uv.fs_stat(store.item_path("cache", "b", "contacts")), nil)
  a.clear()
  T.eq(T.await(function(done)
    a.load("contacts", done)
  end), nil)
end)

T.test("a cache file cannot pass as a secret", function()
  local ls = with_store("pw")
  ls.set_prompt(T.script({ "pw" }).fn)
  T.await(function(done)
    ls.cache("ns").save("pat2", "cached", done)
  end)
  local store = require("locksmith.store")
  vim.uv.fs_copyfile(store.item_path("cache", "ns", "pat2"), store.item_path("items", "ns", "pat2"))
  local value, err = T.await(function(done)
    ls.get("ns", "pat2", done)
  end)
  T.eq(value, nil)
  T.ok(err:find("cannot be decrypted"))
end)

T.test("a locked and declined cache load is nil", function()
  local ls = with_store("pw")
  ls.set_prompt(T.script({ "pw" }).fn)
  T.await(function(done)
    ls.cache("ns").save("x", { 1 }, done)
  end)
  ls.lock()
  ls.set_prompt(T.script({ nil }).fn)
  T.eq(T.await(function(done)
    ls.cache("ns").load("x", done)
  end), nil)
end)

T.test("invalid names and values are programming errors", function()
  local ls = T.fresh()
  T.eq(pcall(ls.get, "..", "x", function() end), false)
  T.eq(pcall(ls.set, "ns", "a/b", "x"), false)
  T.eq(pcall(ls.set, "ns", "x", 42), false)
  T.eq(pcall(ls.cache, "a b"), false)
end)

T.test("unlocking makes Neovim non-dumpable when harden is on", function()
  local ls = T.fresh({ harden = true })
  ls.set_prompt(T.script({ "pw", "pw" }).fn)
  T.await(ls.unlock)
  T.eq(crypto.dumpable(), false)
end)
